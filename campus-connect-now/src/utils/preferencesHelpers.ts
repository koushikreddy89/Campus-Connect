export const formatPreferenceDate = (
  dateInput: Date | string | number,
  timezone: string = 'Asia/Kolkata',
  dateFormat: 'DD/MM/YYYY' | 'MM/DD/YYYY' | 'YYYY-MM-DD' = 'DD/MM/YYYY',
  timeFormat: '12h' | '24h' = '12h'
): string => {
  if (!dateInput) return '';
  try {
    const d = new Date(dateInput);
    if (isNaN(d.getTime())) return '';

    const hour12 = timeFormat === '12h';
    const formatter = new Intl.DateTimeFormat('en-US', {
      timeZone: timezone,
      year: 'numeric',
      month: '2-digit',
      day: '2-digit',
      hour: '2-digit',
      minute: '2-digit',
      hour12: hour12
    });

    const parts = formatter.formatToParts(d);
    const partMap = parts.reduce((acc, p) => {
      acc[p.type] = p.value;
      return acc;
    }, {} as Record<string, string>);

    const { year, month, day, hour, minute, dayPeriod } = partMap;

    let dateStr = `${day}/${month}/${year}`;
    if (dateFormat === 'MM/DD/YYYY') {
      dateStr = `${month}/${day}/${year}`;
    } else if (dateFormat === 'YYYY-MM-DD') {
      dateStr = `${year}-${month}-${day}`;
    }

    const timeStr = dayPeriod ? `${hour}:${minute} ${dayPeriod}` : `${hour}:${minute}`;
    return `${dateStr} ${timeStr}`;
  } catch (err) {
    console.error('Error formatting date:', err);
    return new Date(dateInput).toLocaleString();
  }
};

export const playNotificationSound = (
  sound: 'Default' | 'Chime' | 'Pop' | 'Bell' | 'Campus' | 'Silent',
  volume: number = 80
) => {
  if (sound === 'Silent') return;
  try {
    const AudioContext = window.AudioContext || (window as any).webkitAudioContext;
    if (!AudioContext) return;
    const ctx = new AudioContext();
    const gainNode = ctx.createGain();
    gainNode.gain.setValueAtTime(volume / 100, ctx.currentTime);
    gainNode.connect(ctx.destination);

    const playTone = (freqs: number[], duration: number, type: OscillatorType = 'sine') => {
      freqs.forEach((freq, idx) => {
        const osc = ctx.createOscillator();
        osc.type = type;
        osc.frequency.setValueAtTime(freq, ctx.currentTime + idx * 0.1);
        osc.connect(gainNode);
        osc.start(ctx.currentTime + idx * 0.1);
        osc.stop(ctx.currentTime + idx * 0.1 + duration);
      });
    };

    if (sound === 'Default') {
      playTone([440, 880], 0.15);
    } else if (sound === 'Chime') {
      playTone([523.25, 659.25, 783.99, 1046.50], 0.25);
    } else if (sound === 'Pop') {
      playTone([600, 900], 0.08, 'triangle');
    } else if (sound === 'Chime') {
      playTone([523.25, 659.25, 783.99, 1046.50], 0.25);
    } else if (sound === 'Bell') {
      playTone([880, 880, 880], 0.2);
    } else if (sound === 'Campus') {
      playTone([329.63, 392.00, 523.25, 392.00], 0.3);
    }
  } catch (e) {
    console.warn('Audio playback failed:', e);
  }
};
